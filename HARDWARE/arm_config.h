/**
 * @file    arm_config.h
 * @brief   B 车机械臂参数 —— 1x MG995 + 3x SG90，4 自由度
 *
 * 舵机配给
 *   1 个 MG995  +  3 个 SG90
 *
 * 分配方案（依据力矩核算，6V 供电）
 *   肩举升   -> MG995   需求 0.083 N.m / 可用 0.809  安全系数 9.8
 *   底座回转 -> SG90    只克服惯量，余量极大
 *   腕俯仰   -> SG90    需求 0.011 N.m / 可用 0.151  安全系数 13.7
 *   夹爪开合 -> SG90    主动驱动交叉连杆，开口 32~73mm
 *
 * 为什么这样分
 *   SG90 可用力矩只有 MG995 的 19%，扛不动整条臂。
 *   所以 MG995 必须放在承重的肩关节，SG90 做轻活的回转、腕和夹爪。
 *
 * 通道分配（TIM1 四个通道全部用满）
 *   底座回转  SG90    TIM1_CH1  PA8
 *   肩举升    MG995   TIM1_CH2  PA9
 *   腕俯仰    SG90    TIM1_CH3  PA10
 *   夹爪开合  SG90    TIM1_CH4  PA11
 */

#ifndef ARM_CONFIG_H
#define ARM_CONFIG_H

#include <stdint.h>

/* ============================================================
 * 机械尺寸
 * ============================================================ */
#define ARM_LEN_MM            138.0f   /* 肩枢轴到腕枢轴（05 的 x=138）*/
#define WRIST_LEN_MM           67.0f   /* 腕枢轴到指尖（33 腕 + 34 夹爪）*/
#define SHOULDER_Z_MM         146.0f   /* 肩枢轴离地：5+14+105+22 */

#define GRIPPER_OPEN_MM        54.0f   /* 弹片自然开口，套 40mm 方块 */
#define CUBE_MM                40.0f
#define CUBE_MASS_G            11.3f

/* ============================================================
 * 舵机外形尺寸（用户实测，⚠️ 不要照抄厂家标称）
 *   这些尺寸决定 3D 打印件上安装位的内腔、耳槽、轴让位腔。
 *   弯矩/力矩计算不受影响（只跟质量有关）。
 * ============================================================ */

/* --- MG995（肩举升）--- */
#define MG995_BODY_L           40.5f   /* 壳体长（沿耳距方向）*/
#define MG995_BODY_W           20.0f   /* 壳体宽（落进内腔的方向）*/
#define MG995_BODY_H           39.5f   /* 壳体高（沿轴方向）*/
#define MG995_EAR_SPAN         49.0f   /* 安装耳孔中心距 ⚠️实测 */
#define MG995_EAR_HOLE          2.2f   /* 安装孔径，配 M2.5 自攻 */
#define MG995_EAR_T             2.7f   /* 安装耳厚 */
#define MG995_SHAFT_OUT         5.5f   /* 输出轴凸出壳体 */
#define MG995_FLANGE_D         25.0f   /* 输出法兰直径 */
#define MG995_MASS_G           55.0f

/* --- SG90（底座回转 + 腕俯仰）--- */
#define SG90_BODY_L            22.4f
#define SG90_BODY_W            12.5f
#define SG90_BODY_H            23.8f   /* ⚠️ 壳体高，不含轴 */
#define SG90_TOTAL_H           30.0f   /* ⚠️ 含轴总高 */
#define SG90_SHAFT_OUT         (SG90_TOTAL_H - SG90_BODY_H)  /* = 6.2 */
#define SG90_EAR_SPAN          28.0f   /* 安装耳孔中心距 ⚠️实测 */
#define SG90_EAR_HOLE           1.6f   /* 安装孔径，配 M2 自攻 */
#define SG90_EAR_T              2.5f
#define SG90_MASS_G             9.0f

/* ============================================================
 * 3D 打印件上的安装位尺寸（按上面实测值算出来）
 *   +0.3 是装配余量（3D 打印公差 ±0.3）
 * ============================================================ */
/* MG995 安装位 */
#define MG995_CAVITY_L         (MG995_BODY_L + 0.3f)   /* 40.8 */
#define MG995_CAVITY_W         (MG995_BODY_W + 0.3f)   /* 20.3 */
#define MG995_CAVITY_H         (MG995_BODY_H + 0.3f)   /* 39.8 */
#define MG995_SHAFT_CLEAR      (MG995_SHAFT_OUT + 2.0f) /* 7.5 轴+舵盘让位 */

/* SG90 安装位 */
#define SG90_CAVITY_L          (SG90_BODY_L + 0.3f)    /* 22.7 */
#define SG90_CAVITY_W          (SG90_BODY_W + 0.3f)    /* 12.8 */
#define SG90_CAVITY_H          (SG90_BODY_H + 0.3f)    /* 24.1 ⚠️不能用 22.5 */
#define SG90_SHAFT_CLEAR       (SG90_SHAFT_OUT + 2.0f) /* 8.2 轴+舵盘让位 */

/* ============================================================
 * 自攻螺钉底孔（3D 打印件上预留的孔）
 *   打印孔会缩 0.1~0.2mm，所以底孔要放大一点
 * ============================================================ */
#define PILOT_M2_MM             1.75f   /* 配 M2 自攻（SG90 用）*/
#define PILOT_M25_MM            2.15f   /* 配 M2.5 自攻（MG995 用）*/

/* ============================================================
 * 关节限位（度）
 *   四个舵机都是 180 度行程，装在上游杆件上时相对角只有 +-90 度。
 *   留 5 度余量，防止顶死堵转烧舵机。
 * ============================================================ */
#define SHOULDER_MIN         (-85.0f)
#define SHOULDER_MAX         ( 85.0f)
#define SHOULDER_STOW        (-25.0f)   /* 收起：臂杆 -25 度 */

#define BASE_MIN             (-90.0f)
#define BASE_MAX             ( 90.0f)

#define WRIST_MIN            (-85.0f)

/* --- 夹爪开合（SG90 驱动交叉连杆）---
 *
 * 角度 -> 开口（真实几何实测，见 主动夹爪说明.md）
 *   +30 度 ->  73 mm   （最宽）
 *   +25 度 ->  57 mm   <- 张开位置
 *   +10 度 ->  40 mm
 *    -5 度 ->  33 mm
 *   -10 度 ->  32 mm   （最窄，机构极限）
 *   -20 度 ->  34 mm
 *   -30 度 ->  39 mm   <- 夹持位置
 *   -40 度 ->  48 mm
 *   -45 度 ->  53 mm
 *
 * 注意：机构在 -10 度处是**非单调点**（最窄）。
 *      正常使用范围是 -30 ~ +25，都在单调段上。
 *      不要往 -45 方向走，那里会"反开阔"。
 */
#define GRIPPER_MIN          (-34.0f)   /* 下限（约 41mm）*/
#define GRIPPER_MAX          ( 30.0f)   /* 上限（约 73mm）*/
#define GRIP_OPEN_DEG        ( 25.0f)   /* 张开 57mm（够罩住 40 方块）*/
#define GRIP_CLOSE_DEG       (-30.0f)   /* 闭合 39mm（夹 40 方块）*/
#define GRIP_HOLD_DEG        (-32.0f)   /* 保持 40mm（略松防堵转）*/
#define WRIST_MAX            ( 85.0f)
#define WRIST_HOME           (-65.0f)   /* 收起：腕 -65 度（= -(-25)-90）*/

/* 末端最低允许高度（防臂穿地） */
#define TIP_MIN_Z_MM            8.0f   /* 指尖最低离地（夹 40 方块时约 0）*/

/* ============================================================
 * 舵机 PWM
 *   MG995 和 SG90 脉宽范围一样（500~2500us，50Hz），共用参数。
 *   注意：两者电压不同，MG995 用 6V，SG90 用 4.8~5V。
 *   共用 5V 时 MG995 会略欠力（约 8%），余量 9.9 倍够覆盖。
 * ============================================================ */
#define SERVO_PWM_MIN_US       500
#define SERVO_PWM_MAX_US      2500
#define SERVO_PERIOD_US      20000

/* ============================================================
 * 舵机 ID 与定时器通道
 * ============================================================ */
typedef enum {
    SERVO_BASE = 0,       /* 底座回转  SG90   TIM1_CH1 */
    SERVO_SHOULDER,       /* 肩举升    MG995  TIM1_CH2 */
    SERVO_WRIST,          /* 腕俯仰    SG90   TIM1_CH3 */
    SERVO_GRIPPER,        /* 夹爪开合  SG90   TIM1_CH4  <- 新增 */
    SERVO_COUNT
} servo_id_t;

/* ============================================================
 * 中位标定（上机前必须实测填值）
 *   装好后让关节处于"指令角 0 度"的位置，读此时脉宽，
 *   反算中位指令角填进来。
 * ============================================================ */
#define CAL_BASE_MID          90.0f
#define CAL_SHOULDER_MID      90.0f
#define CAL_WRIST_MID         90.0f
#define CAL_GRIPPER_MID       90.0f   /* 夹爪舵机中位脉冲 */

/* 方向：+1 表示指令角增大时舵机角增大，-1 相反 */
#define CAL_BASE_SIGN         ( 1.0f)
#define CAL_SHOULDER_SIGN     (-1.0f)
#define CAL_WRIST_SIGN        ( 1.0f)
#define CAL_GRIPPER_SIGN      ( 1.0f)   /* 夹爪方向：正 = 角度大 = 开口宽 */

/* ============================================================
 * 运动平滑
 * ============================================================ */
#define MOTION_PERIOD_MS        20      /* 20ms = 50Hz */
#define MOTION_STEP_DEG        0.8f     /* 每周期最大角度增量 */
/* 辅助对准的下压/抬升速度（比手动慢，防止撞地）
 * 12 度/秒 -> 从悬停(-8) 压到 (-23) 约 1.25 秒 */
#define ASSIST_RATE_DEG_PER_S  12.0f
#define SERVO_SETTLE_MS       250

/* ============================================================
 * PS2 手柄映射
 * ============================================================ */
#define PS2_DEADZONE           18

#define PS2_AUTO_HOLD_MS       400

#define PS2_ARM_SCALE_DEG       70.0f
#define PS2_WRIST_STEP_DEG       1.5f

/* ============================================================
 * 自动抓方块序列
 *   IDLE -> AIM -> DESCEND -> LIFT -> DONE
 * ============================================================ */
#define PICK_AIM_SHOULDER      (-8.0f)   /* 悬停在方块上方 */
#define PICK_DESCEND_SHOULDER (-23.0f)   /* 压到方块，夹爪中心 z=25 */
#define PICK_LIFT_SHOULDER      8.0f   /* 抬起 */

/* 腕部水平补偿：腕角 = -肩角 - 90，让夹爪始终朝下 */
#define WRIST_LEVEL_COMP        1

/* ============================================================
 * 夹爪（SG90 驱动交叉连杆，主动）
 * ============================================================ */
/* GRIPPER_HOLD_N 已废弃：主动夹爪不再依赖弹片夹持力 */

/* ============================================================
 * 电源保护
 *   峰值 = MG995 2.5A + SG90 0.7A x3 + 底盘 4.8A = 约 9.4A
 * ============================================================ */
#define POWER_VOLT_MIN_MV     5000
#define SERVO_STALL_MA        2500      /* MG995 */
#define SG90_STALL_MA          700      /* SG90 */

#endif /* ARM_CONFIG_H */
